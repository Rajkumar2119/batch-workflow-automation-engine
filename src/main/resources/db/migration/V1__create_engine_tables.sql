-- Reference data: rate that converts one unit of the currency into GBP
CREATE TABLE exchange_rate (
    currency     VARCHAR(3)     NOT NULL PRIMARY KEY,
    rate_to_gbp  NUMERIC(19, 6) NOT NULL,
    updated_at   TIMESTAMP      NOT NULL
);

-- Output of dailyFeedJob
CREATE TABLE processed_transaction (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    txn_id           VARCHAR(64)    NOT NULL,
    account_id       VARCHAR(10)    NOT NULL,
    business_date    DATE           NOT NULL,
    txn_date         DATE           NOT NULL,
    original_amount  NUMERIC(19, 4) NOT NULL,
    currency         VARCHAR(3)     NOT NULL,
    amount_gbp       NUMERIC(19, 2) NOT NULL,
    description      VARCHAR(255),
    source_file      VARCHAR(255),
    processed_at     TIMESTAMP      NOT NULL,
    CONSTRAINT uk_processed_transaction_txn UNIQUE (txn_id)
);
CREATE INDEX idx_processed_txn_business_date ON processed_transaction (business_date);
CREATE INDEX idx_processed_txn_account_date ON processed_transaction (account_id, txn_date);

-- Records that failed validation, kept for correction and replay
CREATE TABLE rejected_record (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_execution_id  BIGINT        NOT NULL,
    business_date     DATE          NOT NULL,
    source_file       VARCHAR(255),
    line_number       INTEGER,
    raw_record        VARCHAR(1000),
    reason            VARCHAR(500)  NOT NULL,
    created_at        TIMESTAMP     NOT NULL
);
CREATE INDEX idx_rejected_business_date ON rejected_record (business_date);

-- One row per job execution: who triggered it and what it did
CREATE TABLE job_audit (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_execution_id  BIGINT        NOT NULL,
    job_name          VARCHAR(100)  NOT NULL,
    run_date          VARCHAR(10),
    trigger_source    VARCHAR(20)   NOT NULL,
    triggered_by      VARCHAR(100),
    status            VARCHAR(20)   NOT NULL,
    start_time        TIMESTAMP,
    end_time          TIMESTAMP,
    read_count        BIGINT        DEFAULT 0 NOT NULL,
    write_count       BIGINT        DEFAULT 0 NOT NULL,
    skip_count        BIGINT        DEFAULT 0 NOT NULL,
    exit_code         VARCHAR(20),
    exit_description  VARCHAR(2000),
    CONSTRAINT uk_job_audit_execution UNIQUE (job_execution_id)
);
CREATE INDEX idx_job_audit_job_start ON job_audit (job_name, start_time);
CREATE INDEX idx_job_audit_status ON job_audit (status);
